"""
WorkflowState — the shared data structure that flows through the LangGraph graph.

LangGraph requires state to be a TypedDict (or a Pydantic model / dataclass).
A TypedDict is just a regular Python dict with known key names and declared
value types.  There is NO runtime enforcement — it's purely for readability
and IDE type-checking.

Lifecycle:
  main.py          → creates the initial state dict (query, file_content set;
                      retrieved_chunks=[], verdict="" etc.)
  retriever_node   → reads  state["query"]
                     writes state["retrieved_chunks"]
  validator_node   → reads  state["query"], state["file_content"],
                             state["retrieved_chunks"]
                     writes state["verdict"], state["confidence"],
                             state["answer"]
  main.py          → reads state["verdict"], state["confidence"],
                             state["answer"], state["retrieved_chunks"]
                     and returns them as the HTTP response
"""

from typing import TypedDict


class WorkflowState(TypedDict):
    # ---- inputs (set once by main.py, never changed by nodes) ----

    # The user's compliance question, e.g.
    # "Is storing IP addresses without consent a GDPR violation?"
    query: str

    # The contract text the user pasted in (optional — may be empty string).
    # Passed to the LLM together with the retrieved chunks so it can reason
    # against the actual document, not just in the abstract.
    file_content: str

    # The workflow ID generated by the FastAPI backend (e.g. "WF-A3B79C1D").
    # We carry it through state so it ends up in the returned JSON and the
    # caller can match the response to the audit log entry.
    workflow_id: str

    # ---- written by retriever_node ----

    # The list of document text chunks returned by ChromaDB.
    # Starts as an empty list [].  After retriever_node runs it contains
    # up to TOP_K strings, each being one chunk from the knowledge base.
    # Example: ["GDPR Article 4(1): 'personal data' means...", "Recital 30: ..."]
    retrieved_chunks: list[str]

    # ---- written by validator_node ----

    # One of three values: "COMPLIANT", "NON-COMPLIANT", or "UNCERTAIN".
    # Starts as empty string "".
    verdict: str

    # A score from 0.0 to 1.0 representing how confident the LLM is.
    # Starts as 0.0.
    confidence: float

    # The LLM's reasoning / explanation for the verdict.
    # Starts as empty string "".
    answer: str
