"""
LangGraph Worker — entry point.

This service is called by the FastAPI backend (routes/workflow.py) via
  POST http://langgraph-worker:8001/run
It is NOT publicly exposed — no JWT auth is needed here because the
backend already verified the user before forwarding the request.

Phase 3 wires the stub /run handler to the real LangGraph pipeline:
  graph.invoke() → retriever_node → validator_node → structured response
"""

import logging

from fastapi import FastAPI
from pydantic import BaseModel

# Importing graph triggers app/graph.py which compiles the StateGraph.
# Any misconfiguration (missing node, broken edge) raises an error here
# at startup — not when a user makes their first request.
from app.graph import graph
from app.state import WorkflowState

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

app = FastAPI(title="LangGraph Worker", version="2.0.0")


class WorkflowRequest(BaseModel):
    # The user's compliance question
    query: str
    # The contract text pasted in by the user (optional)
    file_content: str = ""
    # The workflow ID generated by the backend — we carry it through unchanged
    workflow_id: str = ""


@app.get("/health")
def health():
    """
    Simple liveness check.  Called by docker-compose healthcheck and the
    backend before routing traffic.
    """
    return {"status": "ok", "service": "langgraph-worker"}


@app.post("/run")
def run_workflow(request: WorkflowRequest):
    """
    Run the full RAG + LLM compliance analysis pipeline.

    1. Build the initial state dict — all output fields start empty.
    2. Call graph.invoke(state) — LangGraph executes:
         retriever_node  → fills state["retrieved_chunks"]
         validator_node  → fills state["verdict"], state["confidence"],
                                   state["answer"]
    3. Pull the final field values out of the returned state and
       return them as the HTTP response body.

    The FastAPI backend (routes/workflow.py) reads verdict, confidence,
    and answer from this response and writes them to the audit log.
    """
    logger.info("Starting workflow %s | query: %.80s...", request.workflow_id, request.query)

    # ── 1. Initial state ──────────────────────────────────────────
    # Inputs are set; all outputs start at their "empty" values.
    # LangGraph nodes will progressively fill in the blanks.
    initial_state: WorkflowState = {
        "query": request.query,
        "file_content": request.file_content,
        "workflow_id": request.workflow_id,
        "retrieved_chunks": [],   # retriever_node fills this
        "verdict": "",            # validator_node fills this
        "confidence": 0.0,        # validator_node fills this
        "answer": "",             # validator_node fills this
    }

    # ── 2. Run the graph ──────────────────────────────────────────
    # graph.invoke() runs synchronously:
    #   - calls retriever_node(state), merges returned dict into state
    #   - calls validator_node(state), merges returned dict into state
    #   - returns the complete final state dict
    # The call blocks until both nodes finish — typically 5-20 seconds
    # because the LLM generation is the slow step.
    final_state: WorkflowState = graph.invoke(initial_state)

    logger.info(
        "Completed workflow %s | verdict=%s confidence=%.2f",
        request.workflow_id,
        final_state["verdict"],
        final_state["confidence"],
    )

    # ── 3. Return response ────────────────────────────────────────
    # The backend's routes/workflow.py expects exactly these keys.
    # retrieved_chunks is included so the frontend can show which
    # documents supported the verdict (explainability).
    return {
        "workflow_id": final_state["workflow_id"],
        "status": "completed",
        "verdict": final_state["verdict"],
        "confidence": final_state["confidence"],
        "answer": final_state["answer"],
        "retrieved_chunks": final_state["retrieved_chunks"],
    }